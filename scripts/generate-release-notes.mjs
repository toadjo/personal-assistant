#!/usr/bin/env node

/**
 * Generate release notes module from CHANGELOG.md
 *
 * This script parses CHANGELOG.md in Keep a Changelog format and generates
 * a TypeScript module with release notes for use in the renderer.
 *
 * Usage: node scripts/generate-release-notes.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

try {
  const changelogPath = join(fileURLToPath(new URL(".", import.meta.url)), "..", "CHANGELOG.md");
  const outputPath = join(
    fileURLToPath(new URL(".", import.meta.url)),
    "..",
    "src",
    "renderer",
    "lib",
    "release-notes.generated.ts"
  );

  const changelogContent = readFileSync(changelogPath, "utf8");

  // Parse Keep a Changelog format
  const releaseNotes = [];
  const sectionRegex = /## \[([0-9.]+)\] - ([0-9-]+)\n([\s\S]*?)(?=## \[|$)/g;

  let match;
  while ((match = sectionRegex.exec(changelogContent)) !== null) {
    const [, version, date, markdown] = match;
    releaseNotes.push({
      version,
      date,
      markdown: markdown.trim()
    });
  }

  // Generate TypeScript module
  const generatedContent = `// This file is auto-generated by scripts/generate-release-notes.mjs
// Do not edit manually.

export type ReleaseNote = {
  version: string;
  date: string;
  markdown: string;
};

export const releaseNotes: ReleaseNote[] = ${JSON.stringify(releaseNotes, null, 2)};

export function getReleaseNote(version: string): ReleaseNote | undefined {
  return releaseNotes.find((note) => note.version === version);
}

export function getLatestReleaseNote(): ReleaseNote | undefined {
  return releaseNotes[0];
}
`;

  writeFileSync(outputPath, generatedContent);
  console.log(`Release notes generated: ${outputPath}`);
  console.log(`Found ${releaseNotes.length} release notes`);
} catch (error) {
  console.error("Failed to generate release notes:", error);
  process.exit(1);
}
